const PaletteMap* palettes::byName(std::string_view name) {
    if (name == "ega") return &kEga;
    if (name == "game") return &kGame;
    if (name == "face") return &kFace;
    if (name == "chase") return &kChase;
    return nullptr;
}

std::span<const std::uint8_t, 128 * 3> mcgaDefaultDac() { return kDefaultDac; }

Palette mcgaPalette(const PaletteMap& map) {
    Palette p;
    auto dac = [](std::size_t i) {
        return Palette::fromVga6(kDefaultDac[i * 3], kDefaultDac[i * 3 + 1], kDefaultDac[i * 3 + 2]);
    };
    for (std::size_t i = 0; i < 128; ++i) p.colors[i] = dac(i);
    // mgfx_set_palette: dac_pal16[i] = default_dac[pal[i]]. (The driver doesn't
    // bound the index; the game's tables only hold 0..15.)
    for (std::size_t i = 0; i < 16; ++i) p.colors[i] = dac(map[i] & 127u);
    return p;
}

int mcgaBorderColor(const PaletteMap& map) {
    // mgfx_set_palette scans pal[15] down to pal[0] for pal[16].
    for (int i = 15; i >= 0; --i)
        if (map[static_cast<std::size_t>(i)] == map[16]) return i;
    return -1;
}

